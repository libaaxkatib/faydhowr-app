// Builds docs/HR_SOMALI_TRANSLATION_REGISTER.md from the catalogue and the sources, so the register can never drift from the code. The file keeps its
// original name (the owner refers to it); it now covers every screen. `npm run i18n:register` writes it; registerFresh.test.ts fails when the committed
// file differs from what this function produces.

import { readFileSync, readdirSync } from 'node:fs';

import { CATEGORIES, categoryOf } from './catalog.ts';
import { AREAS, CATALOGUE } from './messages/index.ts';

type Row = { en: string; so: string; review: string; id?: string; note?: string };

const SRC = new URL('../', import.meta.url);
const BASELINE = JSON.parse(readFileSync(new URL('./baseline/approved-161.json', import.meta.url), 'utf8').replace(/\r\n/g, '\n')) as { messages: { key: string }[] };
const NOTES = readFileSync(new URL('./register-notes.md', import.meta.url), 'utf8').replace(/\r\n/g, '\n').trimEnd();

const CATEGORY_TITLES: Record<string, string> = {
  nav: 'Navigation',
  status: 'Status and stage labels',
  action: 'Actions',
  option: 'Selectable options, labels and headings',
  warning: 'Warnings, notices and empty states',
  confirm: 'Confirmations',
  validation: 'Validation',
  notify: 'Notifications and errors',
};

function sources(directory: URL): { path: string; text: string }[] {
  return readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const child = new URL(entry.name + (entry.isDirectory() ? '/' : ''), directory);
      if (entry.isDirectory()) return entry.name === 'baseline' || entry.name === 'messages' ? [] : sources(child);
      if (!/\.(ts|tsx)$/.test(entry.name) || /\.test\.ts$/.test(entry.name)) return [];

      return [{ path: child.pathname.split('/src/')[1], text: readFileSync(child, 'utf8').replace(/\r\n/g, '\n') }];
    });
}

function refersTo(text: string, prefixes: string[], key: string): boolean {
  if (text.includes(`'${key}'`) || text.includes(`"${key}"`) || text.includes(`\`${key}\``)) return true;
  const base = key.replace(/\.(one|other)$/, '');
  if (base !== key && (text.includes(`'${base}'`) || text.includes(`"${base}"`))) return true;

  return prefixes.some((prefix) => key.startsWith(prefix));
}

function dynamicPrefixes(text: string): string[] {
  const prefixes: string[] = [];
  for (const match of text.matchAll(/tValue(?:Now)?\(\s*['"`]([A-Za-z0-9_.]+)['"`]/g)) prefixes.push(`${match[1]}.`);
  for (const match of text.matchAll(/[`'"]([a-z]+\.[A-Za-z0-9_.]+\.)\$\{/g)) prefixes.push(match[1]);

  return prefixes;
}

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function buildRegister(): string {
  const files = sources(SRC).map((f) => ({ ...f, prefixes: dynamicPrefixes(f.text) }));
  const entries = Object.entries(CATALOGUE) as [string, Row][];
  const locked = new Set(BASELINE.messages.map((m) => m.key));
  const byReview = (review: string) => entries.filter(([, e]) => e.review === review).length;
  const additions = entries.filter(([k, e]) => e.review === 'approved' && !locked.has(k)).length;

  const screensOf = (key: string): string => {
    const names = files.filter((f) => refersTo(f.text, f.prefixes, key)).map((f) => f.path.replace(/^features\/(hrm|marketing|system|customers|auth|dashboard)\//, ''));

    return names.length === 0 ? 'not displayed' : names.slice(0, 6).join(', ') + (names.length > 6 ? `, +${names.length - 6} more` : '');
  };

  const lines: string[] = [];
  lines.push('# Somali translation register');
  lines.push('');
  lines.push(
    'Generated by `npm run i18n:register` (web-panel) from the translation catalogue (`web-panel/src/i18n/messages/*.ts`) and the web-panel sources; a test fails if this file is out of date. ' +
      'The panel is shown in English (the default) or Somali on **every** screen, sign-in included; the choice is kept in the browser under `fayadhowr.ui.language`. ' +
      'Stored values (`applicant`, `damiin_needed`, `waiting`, ...), API fields, permission identifiers, audit-log text and the Excel files produced by the backend are never translated; only the visible label differs.',
  );
  lines.push('');
  lines.push('## How to read it');
  lines.push('');
  lines.push('- **Review**: `approved` = owner-approved text (the ID is the owner\'s review-list ID); `owner-term` = the owner supplied the wording but its review is still open; `proposed` = Somali written for this implementation, not reviewed by a native speaker.');
  lines.push('- **Locked**: `locked` marks the 161 messages the owner declared final, approved and locked on 2026-10-27. Their exact text is protected by an automated test against a fixed baseline.');
  lines.push('- **Screens**: the source files that use the message (the first six); `not displayed` means no source file refers to it.');
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push('| | Messages |');
  lines.push('|---|---|');
  lines.push(`| Total in the catalogue | ${entries.length} |`);
  lines.push(`| **Locked** (owner-approved, final) | ${locked.size} |`);
  lines.push(`| Owner-approved additions (not among the 161) | ${additions} |`);
  lines.push(`| Owner wording, review still open (\`owner-term\`) | ${byReview('owner-term')} |`);
  lines.push(`| Proposed, not yet reviewed | ${byReview('proposed')} |`);
  lines.push('');
  lines.push('| Category | Messages | Locked |');
  lines.push('|---|---|---|');
  for (const category of CATEGORIES) {
    const inCategory = entries.filter(([k]) => categoryOf(k) === category);
    lines.push(`| ${CATEGORY_TITLES[category]} | ${inCategory.length} | ${inCategory.filter(([k]) => locked.has(k)).length} |`);
  }
  lines.push('');
  lines.push('| Area (message file) | Messages |');
  lines.push('|---|---|');
  for (const [area, messages] of Object.entries(AREAS)) lines.push(`| ${area} | ${Object.keys(messages).length} |`);
  lines.push('');
  lines.push(NOTES);
  lines.push('');

  for (const category of CATEGORIES) {
    const inCategory = entries.filter(([k]) => categoryOf(k) === category);
    lines.push(`## ${CATEGORY_TITLES[category]} (${inCategory.length})`);
    lines.push('');
    lines.push('| Key | ID | Locked | English | Somali | Review | Screens | Note |');
    lines.push('|---|---|---|---|---|---|---|---|');
    for (const [key, e] of inCategory) {
      lines.push(`| \`${key}\` | ${e.id ?? ''} | ${locked.has(key) ? 'locked' : ''} | ${cell(e.en)} | ${cell(e.so)} | ${e.review} | ${cell(screensOf(key))} | ${cell(e.note ?? '')} |`);
    }
    lines.push('');
  }

  return lines.join('\n');
}
